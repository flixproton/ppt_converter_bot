# EXTRACTION LOGIC (PPTX & PDF)
# -------------------------------------------------------------
def extract_from_pptx(file_bytes):
    """Extracts titles, text, and speaker notes from PPTX."""
    prs = Presentation(io.BytesIO(file_bytes))
    slides_data = []

    for idx, slide in enumerate(prs.slides, start=1):
        # Title extraction
        title = ""
        if slide.shapes.title and slide.shapes.title.text:
            title = slide.shapes.title.text.strip()
        else:
            title = f"Topic / Slide {idx}"

        # Body text extraction
        content = []
        for shape in slide.shapes:
            if shape.has_text_frame and shape != slide.shapes.title:
                for paragraph in shape.text_frame.paragraphs:
                    text = paragraph.text.strip()
                    if text and text not in content:
                        content.append(text)

        # Presenter Notes extraction
        notes = ""
        if slide.has_notes_slide and slide.notes_slide.notes_text_frame:
            notes = slide.notes_slide.notes_text_frame.text.strip()

        slides_data.append({
            "num": idx,
            "title": title,
            "content": content,
            "notes": notes,
        })
    return slides_data


def extract_from_pdf(file_bytes):
    """Extracts text lines from PDF presentation slides."""
    doc = fitz.open(stream=file_bytes, filetype="pdf")
    slides_data = []

    for idx, page in enumerate(doc, start=1):
        text = page.get_text("text").strip()
        lines = [line.strip() for line in text.split("\n") if line.strip()]

        title = lines[0] if lines else f"Page {idx}"
        content = lines[1:] if len(lines) > 1 else []

        slides_data.append({
            "num": idx,
            "title": title,
            "content": content,
            "notes": "",
        })
    return slides_data


