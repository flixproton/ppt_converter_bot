async def start_command(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Welcome message with brand name."""
    welcome_text = (
        f"👋 **Welcome to {BRAND_NAME}!**\n\n"
        "📄 Send me any **PPTX** or **PDF presentation**, and I will instantly convert it into a "
        "**clean, ink-saving Black & White study notes PDF**!\n\n"
        "✨ **What I do:**\n"
        "• Strips all heavy images & dark backgrounds\n"
        "• Extracts slide text, bullet points & presenter notes\n"
        "• Formats everything into neat, printable A4 pages\n\n"
        "🚀 **Just upload your file here to get started!**"
    )
    await update.message.reply_text(welcome_text, parse_mode="Markdown")


async def handle_document(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Processes uploaded PPTX/PDF and returns the notes PDF."""
    document = update.message.document
    file_name = document.file_name or "presentation"
    file_ext = file_name.split(".")[-1].lower()

    if file_ext not in ["pptx", "pdf"]:
        await update.message.reply_text(
            "⚠️ Please upload a valid **.pptx** or **.pdf** slide file.",
            parse_mode="Markdown",
        )
        return

    status_msg = await update.message.reply_text(
        "⏳ **Downloading and converting into B&W study notes... Please wait.**",
        parse_mode="Markdown",
    )

    try:
        # Download the file from Telegram into memory
        tg_file = await context.bot.get_file(document.file_id)
        file_bytes = await tg_file.download_as_bytearray()

        # Extract content
        if file_ext == "pptx":
            slides_data = extract_from_pptx(file_bytes)
        else:
            slides_data = extract_from_pdf(file_bytes)

        if not slides_data:
            await status_msg.edit_text("❌ Could not extract any readable text from this file.")
            return

        # Generate clean PDF
        output_pdf_bytes = create_bw_notes_pdf(slides_data)

        # Brand the output filename
        base_name = os.path.splitext(file_name)[0]
        output_filename = f"{base_name}_Yash_PPT_Converter_Bot.pdf"

        # Send back to user
        await update.message.reply_document(
            document=io.BytesIO(output_pdf_bytes),
            filename=output_filename,
            caption=f"✅ **Converted successfully by {BRAND_NAME}!**\n📄 Clean Black & White Study Notes.",
            parse_mode="Markdown",
        )
        await status_msg.delete()

    except Exception as e:
        logger.error(f"Error during conversion: {e}", exc_info=True)
        await status_msg.edit_text("❌ An error occurred during conversion. Please make sure the file is not password-protected.")


# -------------------------------------------------------------
# MAIN APPLICATION
# -------------------------------------------------------------
def main():
    # 1. Start the dummy HTTP server in a separate background thread for Render
    server_thread = threading.Thread(target=run_dummy_server, daemon=True)
    server_thread.start()

    # 2. Start the Telegram Bot
    if BOT_TOKEN == "YOUR_TELEGRAM_BOT_TOKEN_HERE" or not BOT_TOKEN:
        print("ERROR: BOT_TOKEN is missing! Please set your environment variable or edit main.py.")
        return

    app = ApplicationBuilder().token(BOT_TOKEN).build()

    app.add_handler(CommandHandler("start", start_command))
    app.add_handler(CommandHandler("help", start_command))
    app.add_handler(MessageHandler(filters.Document.ALL, handle_document))

    logger.info(f"{BRAND_NAME} is running...")
    app.run_polling()


if __name__ == "__main__":
    main()
