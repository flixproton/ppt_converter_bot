# B&W PDF GENERATION
# -------------------------------------------------------------
class BWNotesPDF(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(100, 100, 100)
        self.cell(0, 8, f"Study Notes • {BRAND_NAME}", border=0, align="R")
        self.ln(10)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(120, 120, 120)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by {BRAND_NAME}", align="C")


def create_bw_notes_pdf(slides_data):
    """Generates a clean black & white A4 printable PDF."""
    pdf = BWNotesPDF(orientation="P", unit="mm", format="A4")
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    for item in slides_data:
        # Subtle horizontal divider
        pdf.set_draw_color(210, 210, 210)
        pdf.line(10, pdf.get_y(), 200, pdf.get_y())
        pdf.ln(3)

        # Slide Number & Title
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(0, 0, 0)
        title_text = f"[{item['num']}] {item['title']}".encode("latin-1", "replace").decode("latin-1")
        pdf.multi_cell(0, 6, title_text)
        pdf.ln(2)

        # Bullet Points
        if item["content"]:
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(30, 30, 30)
            for bullet in item["content"]:
                clean_bullet = f"• {bullet}".encode("latin-1", "replace").decode("latin-1")
                pdf.multi_cell(0, 5.5, clean_bullet)
            pdf.ln(2)

        # Speaker / Presenter Notes
        if item["notes"]:
            pdf.set_font("Helvetica", "I", 9)
            pdf.set_text_color(70, 70, 70)
            notes_text = f"Speaker Notes: {item['notes']}".encode("latin-1", "replace").decode("latin-1")
            pdf.multi_cell(0, 5, notes_text)
            pdf.ln(2)

        pdf.ln(4)

    return bytes(pdf.output())


